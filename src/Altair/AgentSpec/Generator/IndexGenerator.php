namespace Altair\AgentSpec\Generator;

use Altair\AgentSpec\Model\ModuleManifest;
use Altair\AgentSpec\Model\PackageDescriptor;

/**
 * Renders the global `.agent/MANIFEST.md` index — one line per package with
 * a link to its detailed manifest, then one per contributing host module.
 * Output is deterministic; without modules it is unchanged.
 */
class IndexGenerator
{
    public const string HEADER = '# Altair Framework — Agent Manifest Index';

    /**
     * @param list<PackageDescriptor> $packages Pre-sorted by package name.
     * @param list<ModuleManifest>     $modules  Pre-sorted by module name.
     */
    public function render(array $packages, string $packagesDirectory = 'packages', array $modules = []): string
    {
        $body = [self::HEADER, ''];

        if ($packages !== [] || $modules === []) {
            $body = [...$body, ...$this->packageRows($packages, $packagesDirectory)];
        }

        if ($modules !== []) {
            $body = [...$body, ...$this->moduleRows($modules, $packages !== [])];
        }

        return implode("\n", $body) . "\n";
    }

    /**
     * @param list<PackageDescriptor> $packages
     *
     * @return list<string>
     */
    private function packageRows(array $packages, string $packagesDirectory): array
    {
        $body = [
            'Machine-readable descriptions of every framework sub-package, generated by `univeros/agent-spec`.',
            '',
            '| Package | Namespace | Description |',
            '|---|---|---|',
        ];

        foreach ($packages as $package) {
            $link = \sprintf('[%s](%s/%s.md)', $package->packageName, $packagesDirectory, $package->manifestSlug);
            $body[] = \sprintf(
                '| %s | `%s` | %s |',
                $link,
                $package->rootNamespace,
                $this->escapeTable($package->description),
            );
        }

        return $body;
    }

    /**
     * @param list<ModuleManifest> $modules
     *
     * @return list<string>
     */
    private function moduleRows(array $modules, bool $afterPackages): array
    {
        $body = $afterPackages ? [''] : [];
        $body = [
            ...$body,
            '## Modules',
            '',
            "Sections contributed by the host's registered modules.",
            '',
            '| Module | Description |',
            '|---|---|',
        ];

        foreach ($modules as $module) {
            $body[] = \sprintf('| [%s](%s) | %s |', $module->name, $module->path(), $this->escapeTable($module->description));
        }

        return $body;
    }

    private function escapeTable(string $value): string
    {
        return str_replace('|', '\\|', $value);
    }
}
